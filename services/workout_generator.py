def format_workout(split, exp="beginner"):
    t = TEMPLATES.get(split)
    if not t:
        return "Не найдено"
    txt = "🏋️ **" + t["title"] + "**\n\n"
    for name, exs in t[exp]:
        txt += "━━━ " + name + " ━━━\n"
        for e in exs:
            txt += "  🏋️ " + e + "\n"
        txt += "\n"
    txt += "📅 " + t["schedule"] + "\n\n"
    txt += "💡 Разминка 5-10 мин, отдых 60-90с / 2-3 мин"
    return txt

