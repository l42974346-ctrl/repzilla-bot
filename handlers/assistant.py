@assistant_router.message(F.text == "📚 База Знаний")
async def assistant_menu(message: Message):
    await message.answer("Интеллектуальная энциклопедия Repzilla. Выбери тему:", reply_markup=assistant_kb())

@assistant_router.message(F.text.in_(TEXTS.keys()))
async def send_text(message: Message):
    await db.add_xp(message.from_user.id, 5)
    await message.answer(TEXTS[message.text], parse_mode="Markdown")

@assistant_router.message(F.text == "Цитаты легенд")
async def quotes(message: Message):
    q = random.choice(QUOTES)
    await db.add_xp(message.from_user.id, 5)
    await message.answer(q, parse_mode="Markdown")
